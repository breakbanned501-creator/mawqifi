export const translations = {
  ar: arabicTranslations,
  en: englishTranslations,
} as const;

/** Allows incremental adoption while the catalog is expanded with new UI copy. */
export type TranslationKey = keyof typeof arabicTranslations | (string & {});

export function isLocale(value: unknown): value is Locale {
  return value === 'ar' || value === 'en';
}

export function getTextDirection(locale: Locale): TextDirection {
  return localeMetadata[locale].dir;
}

export function getLocaleTag(locale: Locale): string {
  return localeMetadata[locale].tag;
}

export function readStoredLocale(): Locale | null {
  if (typeof window === 'undefined') return null;

  try {
    const value = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    return isLocale(value) ? value : null;
  } catch {
    return null;
  }
}

export function persistLocale(locale: Locale): void {
  if (typeof window === 'undefined') return;

  try {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // Local storage may be unavailable in private or restricted browser contexts.
  }
}

export function interpolate(template: string, values?: TranslationValues): string {
  if (!values) return template;

  return template.replace(/{{\s*([\w.-]+)\s*}}/g, (placeholder, key: string) => {
    const value = values[key];
    return value === null || value === undefined ? placeholder : String(value);
  });
}

export function translate(locale: Locale, key: TranslationKey, values?: TranslationValues): string {
  const localeDictionary = translations[locale] as Record<string, string>;
  const fallbackDictionary = translations.ar as Record<string, string>;
  const template = localeDictionary[key] ?? fallbackDictionary[key] ?? key;
  return interpolate(template, values);
}

export function formatLocaleDate(
  locale: Locale,
  value: Date | string | number,
  options: Intl.DateTimeFormatOptions = {},
): string {
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return '';
  return new Intl.DateTimeFormat(getLocaleTag(locale), options).format(date);
}

export function formatLocaleNumber(
  locale: Locale,
  value: number,
  options: Intl.NumberFormatOptions = {},
): string {
  return new Intl.NumberFormat(getLocaleTag(locale), options).format(value);
}

export function formatLocaleRelativeTime(
  locale: Locale,
  value: number,
  unit: Intl.RelativeTimeFormatUnit,
  options: Intl.RelativeTimeFormatOptions = { numeric: 'auto' },
): string {
  return new Intl.RelativeTimeFormat(getLocaleTag(locale), options).format(value, unit);
}
